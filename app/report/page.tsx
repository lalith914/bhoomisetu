"use client";

import Link from "next/link";
import { Suspense, useEffect, useState } from "react";
import { useSearchParams } from "next/navigation";

type ReportData = {
  analysis: any;
  scenes: any[];
  soil: any;
  elevation: number | null;
  raster?: any;
};

function ReportContent() {
  const params = useSearchParams();
  const id = params.get("id") || params.get("parcel") || "";
  const lat = Number(params.get("lat"));
  const lng = Number(params.get("lng"));
  const validLocation = Number.isFinite(lat) && Number.isFinite(lng);

  const [data, setData] = useState<ReportData | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  useEffect(() => {
    if (!validLocation) return;

    let active = true;
    setLoading(true);
    setError("");

    fetch("/api/intelligence", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ reportId: id || `parcel-${lat}-${lng}`, lat, lng }),
      cache: "no-store",
    })
      .then(async (response) => {
        const result = await response.json();
        if (!response.ok) {
          throw new Error(result.error || "Unable to generate the report.");
        }
        return result;
      })
      .then((result) => {
        if (active) setData(result);
      })
      .catch((err) => {
        if (active) {
          setError(err instanceof Error ? err.message : "Unable to generate the report.");
        }
      })
      .finally(() => {
        if (active) setLoading(false);
      });

    return () => {
      active = false;
    };
  }, [id, lat, lng, validLocation]);

  const analysis = data?.analysis;
  const score = analysis?.scores?.overall;
  const scene = data?.scenes?.[0];

  return (
    <main className="report-page">
      <header className="report-head">
        <Link href="/" className="console-wordmark">BHOOMI<span>SETU</span></Link>
        <div>
          <button onClick={() => window.print()} disabled={!data}>PRINT / SAVE PDF ↗</button>
          <Link href="/intelligence">BACK TO INTELLIGENCE</Link>
        </div>
      </header>

      <section className="report-title">
        <span>GENERATED BY BHOOMISETU GEOINTELLIGENCE ENGINE</span>
        <h1>Land Intelligence<br /><em>Report.</em></h1>
        <p>Parcel {id || "—"} · {validLocation ? `${lat.toFixed(5)}° N / ${lng.toFixed(5)}° E` : "Location required"} · LIVE EVIDENCE PIPELINE</p>
      </section>

      {!validLocation && (
        <section className="report-preview">
          <span>LOCATION REQUIRED</span>
          <h2>Select a parcel first.</h2>
          <p>Return to Explore and select a land parcel before generating the intelligence report.</p>
          <Link href="/explore" className="console-action">OPEN EXPLORE ↗</Link>
        </section>
      )}

      {error && (
        <section className="intel-error">
          <span>REPORT ENGINE</span>
          <strong>{error}</strong>
          <p>Check the connected satellite, soil, elevation, raster and AI providers.</p>
        </section>
      )}

      {loading && (
        <section className="report-preview">
          <span>GENERATING</span>
          <h2>Running parcel intelligence...</h2>
          <p>Searching satellite acquisitions and assembling the evidence-backed report.</p>
        </section>
      )}

      {data && (
        <section className="report-grid">
          <div className="report-block report-score"><span>LAND INTELLIGENCE SCORE</span><b>{score ?? "—"}</b><small>{analysis?.confidence != null ? `AI CONFIDENCE ${analysis.confidence}` : "EVIDENCE SCORE"}</small></div>
          <div className="report-block"><span>PARCEL PROFILE</span><h2>{id || "Selected Land"}</h2><p>{validLocation ? `${lat.toFixed(5)}° N · ${lng.toFixed(5)}° E` : "—"}</p><dl><div><dt>ELEVATION</dt><dd>{data.elevation ?? "—"} M</dd></div><div><dt>SCENE</dt><dd>{scene?.date || "—"}</dd></div><div><dt>PLATFORM</dt><dd>{scene?.platform || "—"}</dd></div><div><dt>CLOUD</dt><dd>{scene ? `${Number(scene.cloudCover).toFixed(1)}%` : "—"}</dd></div></dl></div>
          <div className="report-block full"><span>INTELLIGENCE SUMMARY</span><p className="large">{analysis?.summary || "No AI summary returned."}</p></div>
          <div className="report-block"><span>SOIL</span><h2>{analysis?.soil?.status || "UNAVAILABLE"}</h2><p>{analysis?.soil?.evidence || "No soil evidence returned."}</p><small>{analysis?.soil?.limitations || ""}</small></div>
          <div className="report-block"><span>WATER + TERRAIN</span><h2>{analysis?.water?.status || "UNAVAILABLE"}</h2><p>{analysis?.water?.evidence || "No water evidence returned."}</p><p>{analysis?.terrain?.evidence || "No terrain evidence returned."}</p></div>
          <div className="report-block full"><span>VEGETATION + AGRICULTURE</span><p className="large">{analysis?.vegetation?.evidence || "No vegetation evidence returned."} {analysis?.agriculture?.evidence || "No agriculture evidence returned."}</p></div>
          <div className="report-block"><span>RECOMMENDED USE</span><h2>{analysis?.recommendedUses?.[0] || "NO RECOMMENDATION"}</h2><p>{(analysis?.recommendedUses || []).slice(1).join(" · ")}</p></div>
          <div className="report-block"><span>RISKS / LIMITATIONS</span>{(analysis?.risks || []).length > 0 ? analysis.risks.map((risk: string) => <p key={risk}>· {risk}</p>) : <p>No risk information returned.</p>}<div className="report-tags"><b>SOIL {analysis?.scores?.soil ?? "—"}</b><b>WATER {analysis?.scores?.water ?? "—"}</b><b>TERRAIN {analysis?.scores?.terrain ?? "—"}</b></div></div>
          <div className="report-block full"><span>SATELLITE HISTORY</span><div className="report-scenes">{(data.scenes || []).slice(0, 8).map((item: any) => <div key={item.id}><strong>{String(item.date || "").slice(0, 10)}</strong><span>{item.platform || "—"}</span><small>{Number(item.cloudCover || 0).toFixed(1)}% CLOUD</small></div>)}</div></div>
        </section>
      )}

      <footer>LAND ID {id || "—"} · GENERATED {new Date().getFullYear()} · BHOOMISETU / LAND INTELLIGENCE SYSTEM</footer>
    </main>
  );
}

export default function ReportPage() {
  return <Suspense fallback={null}><ReportContent /></Suspense>;
}
